# =========================================================
# PREDICTION FUNCTION
# =========================================================

def run_prediction(img_path):

    results = model(
        img_path,
        imgsz=640,
        conf=0.25,
        verbose=False
    )[0]

    boxes = results.boxes

    predictions = []

    for box in boxes:
        cls = int(box.cls[0])
        conf = float(box.conf[0]) * 100
        name = model.names[cls]

        predictions.append({
            "name": name,
            "conf": round(conf, 2)
        })

    result_path = "result.jpg"
    results.save(result_path)

    return result_path, predictions

