def generate_pdf(input_img, result_img, predictions):

    doc = SimpleDocTemplate(
        "report.pdf",
        pagesize=A4
    )

    styles = getSampleStyleSheet()
    story = []

    # TITLE
    title = Paragraph(
        "Chest X-ray AI Detection Report",
        styles['Title']
    )

    story.append(title)
    story.append(Spacer(1, 20))

    # INPUT IMAGE
    story.append(
        Paragraph("Input X-ray Image", styles['Heading2'])
    )

    story.append(
        PDFImage(input_img, width=400, height=300)
    )

    story.append(Spacer(1, 20))

    # RESULT IMAGE
    story.append(
        Paragraph("AI Detection Result", styles['Heading2'])
    )

    story.append(
        PDFImage(result_img, width=400, height=300)
    )

    story.append(Spacer(1, 20))

    # TABLE
    table_data = [["Disease", "Confidence %"]]

    if len(predictions) == 0:
        table_data.append(["No abnormality detected", "100%"])
    else:
        for p in predictions:
            table_data.append([
                p["name"],
                f'{p["conf"]}%'
            ])

    table = Table(table_data, colWidths=[250, 150])

    table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.darkblue),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('ALIGN', (0,0), (-1,-1), 'CENTER'),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('GRID', (0,0), (-1,-1), 1, colors.grey),
        ('BOTTOMPADDING', (0,0), (-1,0), 12),
    ]))

    story.append(table)
    story.append(Spacer(1, 25))

    # DISCLAIMER
    disclaimer = Paragraph(
        "<i>This report is generated by AI for educational and research purposes only.</i>",
        styles['Italic']
    )

    story.append(disclaimer)

    doc.build(story)

